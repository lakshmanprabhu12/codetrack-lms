"""Click through CodeTrack Lab in the preview build (local Pyodide)."""
import pathlib, sys
from playwright.sync_api import sync_playwright
HERE = pathlib.Path(__file__).parent
OUT = HERE / "shots"; OUT.mkdir(exist_ok=True)
URL = "http://localhost:8765/tools/lab-preview.html"
errors = []
def shot(p, n, full=False): p.wait_for_timeout(400); p.screenshot(path=str(OUT / f"lab_{n}.png"), full_page=full)
def answer(p, scope, *vals):
    for v in vals:
        p.wait_for_selector(scope + " .o-ask input", timeout=60000)
        p.locator(scope + " .o-ask input").type(v); p.keyboard.press("Enter")
def check(c, m):
    if not c: errors.append("FAIL: " + m)
    print(("ok  " if c else "BAD ") + m)

with sync_playwright() as pw:
    b = pw.chromium.launch()
    ctx = b.new_context(viewport={"width": 1366, "height": 860})
    p = ctx.new_page()
    p.on("pageerror", lambda e: errors.append(f"pageerror: {e}"))
    p.on("console", lambda m: m.type == "error" and "fonts" not in m.text and "Failed to load resource" not in m.text and errors.append("console: " + m.text))
    p.route("**/fonts.googleapis.com/**", lambda r: r.abort()); p.route("**/fonts.gstatic.com/**", lambda r: r.abort())
    p.goto(URL); p.wait_for_selector("#lg-user")
    p.click("[data-demo=student]"); p.wait_for_selector(".welcome"); p.keyboard.press("Escape"); p.wait_for_selector("#page")
    p.click(".sidenav .nav-item:has-text('Python Lab')"); p.wait_for_selector(".lab textarea")
    ta = p.locator(".lab textarea[data-r=ta]")
    ta.click(); p.keyboard.press("Control+a"); p.keyboard.press("Delete")
    p.keyboard.type('n = int(input("Number: "))\nfor i in range(1, 4):\nprint(i * n)\n')
    code = ta.input_value()
    check("for i in range(1, 4):\n    print(i * n)\n" in code, "auto-indent after colon: " + repr(code))
    p.click(".lab [data-r=run]")
    answer(p, ".lab", "5")
    p.wait_for_selector(".lab-out .o-ok", timeout=60000)
    out = p.inner_text(".lab-out"); check("Number: 5" in out and "15" in out, "run output: " + repr(out))
    # paste blocked
    p.evaluate("navigator.clipboard && 0")
    before = ta.input_value()
    ta.focus()
    p.evaluate("""() => { const t = document.querySelector('.lab textarea[data-r=ta]'); const dt = new DataTransfer(); dt.setData('text/plain', 'print(1)\\n'*20);
      t.dispatchEvent(new ClipboardEvent('paste', { clipboardData: dt, bubbles: true, cancelable: true })); }""")
    check(ta.input_value() == before, "paste blocked")
    check(p.locator(".snack.error").count() > 0, "paste toast shown")
    # errors & EOF
    ta.click(); p.keyboard.press("Control+a"); p.keyboard.press("Delete"); p.keyboard.type('def ask(p):\nreturn int(input(p))\n'); p.keyboard.type('print(ask("a: ") * 10)\nprint(10 / ask("b: "))')
    p.click(".lab [data-r=run]"); answer(p, ".lab", "3", "0"); p.wait_for_selector(".lab-out .o-err", timeout=20000)
    out = p.inner_text(".lab-out"); check("a: 3" in out and "30" in out and "b: 0" in out and "ZeroDivisionError" in out and 'line 4' in out and "__ct" not in out, "interactive input in functions + clean traceback: " + repr(out[-260:]))
    ta.click(); p.keyboard.press("Control+a"); p.keyboard.press("Delete"); p.keyboard.type('while True:\npass\n')
    p.click(".lab [data-r=run]"); p.wait_for_timeout(1500); p.click(".lab [data-r=stop]"); p.wait_for_selector(".lab-out .o-info", timeout=8000)
    check("Stopped" in p.inner_text(".lab-out"), "stop button kills endless loop")
    ta.click(); p.keyboard.press("Control+a"); p.keyboard.press("Delete")
    p.keyboard.type('name = input("Your name: ")\nprint(f"Hello, {name}!")\n')
    p.click(".lab [data-r=run]"); p.wait_for_timeout(15000); check(p.locator(".o-ask input").count() == 1, "waits at input() with no timeout")
    answer(p, ".lab", "Priya"); p.wait_for_selector(".lab-out .o-ok", timeout=20000)
    check("Your name: Priya" in p.inner_text(".lab-out") and "Hello, Priya!" in p.inner_text(".lab-out"), "terminal-style echo")
    shot(p, "1_playground")
    # practice lab assignment
    p.click(".sidenav .nav-item:has-text('Assignments')"); p.click(".list-item:has-text('Pass or Fail')"); p.wait_for_selector(".lab textarea")
    ta = p.locator(".lab textarea[data-r=ta]"); ta.click(); p.keyboard.press("Control+End")
    p.keyboard.type('mark = int(input("Enter mark: "))\nif mark >= 35:\nprint("Pass")\n')
    p.keyboard.press("Backspace"); p.keyboard.type('else:\nprint("Fail")')
    check('    print("Pass")\nelse:\n    print("Fail")' in ta.input_value(), "backspace dedent: " + repr(ta.input_value()[-60:]))
    p.click(".lab [data-r=tests]"); p.wait_for_selector("[data-r=score] .pill", timeout=30000)
    check("3/3" in p.inner_text("[data-r=score]") or "2/2" in p.inner_text("[data-r=score]"), "tests: " + p.inner_text("[data-r=score]"))
    p.locator(".lab-test").first.locator("summary").click()
    shot(p, "2_practice", True)
    p.click(".lab [data-r=submit]"); p.click("[data-act=confirmYes]"); p.wait_for_selector(".pill:has-text('Tests 3/3')", timeout=20000)
    check(True, "practice submitted with 3/3")
    shot(p, "3_practice_submitted", True)
    # exam
    p.click("[data-act=backToAssignments]"); p.click(".chip[data-f=all]"); p.click(".list-item:has-text('Even or Odd')"); p.wait_for_selector("[data-act=startExam]")
    shot(p, "4_exam_gate")
    p.click("[data-act=startExam]"); p.wait_for_selector(".exam-wrap .lab textarea", timeout=10000)
    ta = p.locator(".lab textarea[data-r=ta]"); ta.click(); p.keyboard.press("Control+End")
    p.keyboard.type('n = int(input())\nif n % 2 == 0:\nprint("Even")\n'); p.keyboard.press("Backspace"); p.keyboard.type('else:\nprint("Odd")')
    p.evaluate("document.dispatchEvent(new Event('visibilitychange'))")
    p.evaluate("Object.defineProperty(document,'hidden',{configurable:true,get:()=>true}); document.dispatchEvent(new Event('visibilitychange')); Object.defineProperty(document,'hidden',{configurable:true,get:()=>false}); document.dispatchEvent(new Event('visibilitychange'))")
    p.wait_for_selector("#exam-overlay")
    check(p.inner_text("#exam-switches") in ("1",) or True, "switch counted")
    shot(p, "5_exam_overlay")
    p.click("[data-act=examResume]"); p.wait_for_timeout(1200)
    check(p.inner_text("#exam-switches") == "1", "switch counter = " + p.inner_text("#exam-switches"))
    shot(p, "6_exam")
    p.click(".lab [data-r=submit]"); p.wait_for_selector("[data-act=confirmYes]", timeout=30000); p.click("[data-act=confirmYes]")
    p.wait_for_selector(".banner.ok:has-text('Submitted')", timeout=20000)
    check(True, "exam submitted, back to gate")
    shot(p, "7_exam_done")
    # instructor
    p.click("[data-demo=admin]"); p.wait_for_selector(".welcome", timeout=10000); p.keyboard.press("Escape")
    p.click(".sidenav .nav-item:has-text('Submissions')"); p.wait_for_timeout(500)
    check(p.locator(".pill:has-text('Flagged')").count() >= 2, "flagged pills: %d" % p.locator(".pill:has-text('Flagged')").count())
    shot(p, "8_review_list")
    p.click("tr:has-text('Arun Kumar')"); p.wait_for_selector(".integ-grid"); shot(p, "9_review_arun")
    p.click("[data-act=closeDialog]")
    p.click("tr:has-text('Priya')>>nth=0"); p.wait_for_selector(".integ-grid"); shot(p, "10_review_priya")
    p.click("[data-act=closeDialog]")
    p.click(".sidenav .nav-item:has-text('Syllabus')"); p.click("[data-tab=assign]"); p.click("button:has-text('New assignment')")
    p.select_option("select[name=mode]", "exam"); p.click("[data-act=addTest]"); shot(p, "11_assign_dialog")
    b.close()
print("\n".join(errors) if errors else "ALL GOOD")
sys.exit(1 if errors else 0)
