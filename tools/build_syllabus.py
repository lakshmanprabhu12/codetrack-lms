def day_obj(row, track):
    day, title, scrum, paper, code, outcomes = row[:6]
    did = f"d{day:02d}" if track == "common" else f"d{day:02d}-{track}"
    return {"id": did, "day": day, "week": week_of(day), "date": dates[day - 1], "track": track,
            "title": title, "scrum": scrum, "paper": paper, "code": code, "outcomes": outcomes}

def assign_obj(row, track, due_override=None):
    day = row[0]
    did = f"d{day:02d}" if track == "common" else f"d{day:02d}-{track}"
    aid = f"a{day:02d}" if track == "common" else f"a{day:02d}-{track}"
    return {"id": aid, "dayId": did, "track": track, "title": row[6], "description": row[7],
            "due": due_override or f"{dates[day - 1]}T23:59", "active": True}

days, assignments = [], []
for row in COMMON + [DAY21]:
    days.append(day_obj(row, "common"))
    assignments.append(assign_obj(row, "common"))
for t, rows in TRACK_DAYS.items():
    for row in rows:
        days.append(day_obj(row, t))
        due = f"{dates[20]}T09:00" if row[0] == 20 else None   # capstone due before presentations
        assignments.append(assign_obj(row, t, due))

days.sort(key=lambda x: (x["day"], x["track"] != "common", x["track"]))
syllabus = {"version": 1, "course": "Python Basics Internship", "tracks": TRACKS,
            "weeks": WEEKS, "days": days, "assignments": assignments}

(ROOT / "syllabus.json").write_text(json.dumps(syllabus, indent=2, ensure_ascii=False), encoding="utf-8")
